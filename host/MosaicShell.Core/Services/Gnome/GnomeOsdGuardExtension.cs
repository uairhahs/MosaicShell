using System.Text.Json;
using System.Text.RegularExpressions;
using MosaicShell.Core.HubShell;
using MosaicShell.Core.Services.Kde;

namespace MosaicShell.Core.Services.Gnome
{
    /// <summary>
    /// MosaicShell's GNOME Shell extension. It shows MosaicShell in the top bar while the Host owns
    /// <see cref="GnomeHubPresencePolicy.BusName"/> (GNOME has no tray of its own), and hides Shell's volume and
    /// brightness pop-ups while Tessera shows its own. GNOME
    /// exposes no way to hide them (only ShowOSD), and in GNOME 51 every pop-up, from Shell's own keys or from ShowOSD,
    /// passes through <c>OsdWindowManager._showOsdWindow(monitorIndex, icon, label, level, maxLevel)</c>. The extension
    /// wraps that one method and skips it for the icons <see cref="HiddenIconPrefixes"/> names while the guard name
    /// (<see cref="KWinOsdScriptPolicy.GuardBusName"/>, the same as on KDE) has an owner; Tessera owns it while armed,
    /// so a closed or crashed Host gives Shell its pop-ups back. The script is generated from these members, so the
    /// rule tested here is the rule Shell runs. Kept pure so it is tested on every OS.
    /// </summary>
    public static partial class GnomeOsdGuardExtension
    {
        public const string Uuid = "osd-guard@mosaicshell";
        public const string ShellSchema = "org.gnome.shell";
        public const string EnabledKey = "enabled-extensions";
        public const string DisableUserExtensionsKey = "disable-user-extensions";

        /// <summary>Volume and brightness, as KDE hides; the microphone and keyboard backlight pop-ups stay.</summary>
        public static IReadOnlyList<string> HiddenIconPrefixes { get; } = ["audio-volume", "display-brightness"];

        /// <summary>ES module extensions (45) up to the GNOME this was checked on (51).</summary>
        private static readonly string[] ShellVersions = ["45", "46", "47", "48", "49", "50", "51"];

        public static string MetadataJson { get; } = JsonSerializer.Serialize(new Dictionary<string, object>
        {
            ["uuid"] = Uuid,
            ["name"] = "MosaicShell",
            ["description"] = "Shows MosaicShell in the top bar while it runs, and hides GNOME's volume and brightness pop-ups while MosaicShell's Tessera shows its own.",
            ["shell-version"] = ShellVersions,
            ["url"] = "https://github.com/uairhahs/MosaicShell",
        }, new JsonSerializerOptions { WriteIndented = true }) + "\n";

        public static string ExtensionJs { get; } = $$"""
            // Generated by MosaicShell (GnomeOsdGuardExtension); rewritten when MosaicShell starts.
            import Gio from 'gi://Gio';
            import GLib from 'gi://GLib';
            import GObject from 'gi://GObject';
            import St from 'gi://St';
            import * as Main from 'resource:///org/gnome/shell/ui/main.js';
            import * as PanelMenu from 'resource:///org/gnome/shell/ui/panelMenu.js';
            import * as PopupMenu from 'resource:///org/gnome/shell/ui/popupMenu.js';
            import {Extension} from 'resource:///org/gnome/shell/extensions/extension.js';

            const GUARD = {{JsonSerializer.Serialize(KWinOsdScriptPolicy.GuardBusName)}};
            const HIDDEN = {{JsonSerializer.Serialize(HiddenIconPrefixes)}};
            const HUB = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.BusName)}};
            const HUB_PATH = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.ObjectPath)}};
            const HUB_IFACE = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.Interface)}};
            const SHOW_HUB = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.ShowHubMethod)}};
            const QUIT = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.QuitMethod)}};
            const MODULES = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.ModulesMethod)}};
            const SET_MODULE_ON = {{JsonSerializer.Serialize(GnomeHubPresencePolicy.SetModuleOnMethod)}};
            const OPEN_LABEL = {{JsonSerializer.Serialize(TrayMenu.OpenLabel)}};
            const QUIT_LABEL = {{JsonSerializer.Serialize(TrayMenu.QuitLabel)}};
            const ICON = {{JsonSerializer.Serialize(PanelIconFile)}};

            function callHub(method, args = null) {
                Gio.DBus.session.call(HUB, HUB_PATH, HUB_IFACE, method, args, null, Gio.DBusCallFlags.NONE, -1, null, null);
            }

            // MosaicShell in the top bar: GNOME has no tray of its own, so this is how a closed Hub comes back.
            const HubIndicator = GObject.registerClass(
            class HubIndicator extends PanelMenu.Button {
                _init(dir) {
                    super._init(0.0, 'MosaicShell');
                    this.add_child(new St.Icon({
                        gicon: new Gio.FileIcon({file: dir.get_child(ICON)}),
                        style_class: 'system-status-icon',
                    }));
                    // A switch per installed module (U24), read from the Host each time the menu opens.
                    this._modules = new PopupMenu.PopupMenuSection();
                    this.menu.addMenuItem(this._modules);
                    this.menu.connect('open-state-changed', (_menu, open) => {
                        if (open)
                            this._fillModules();
                    });
                    const open = new PopupMenu.PopupMenuItem(OPEN_LABEL);
                    open.connect('activate', () => callHub(SHOW_HUB));
                    this.menu.addMenuItem(open);
                    this.menu.addMenuItem(new PopupMenu.PopupSeparatorMenuItem());
                    const quit = new PopupMenu.PopupMenuItem(QUIT_LABEL);
                    quit.connect('activate', () => callHub(QUIT));
                    this.menu.addMenuItem(quit);
                }

                _fillModules() {
                    Gio.DBus.session.call(HUB, HUB_PATH, HUB_IFACE, MODULES, null, new GLib.VariantType('(a(ssb))'),
                        Gio.DBusCallFlags.NONE, -1, null, (connection, result) => {
                            let modules;
                            try {
                                [modules] = connection.call_finish(result).deepUnpack();
                            } catch (e) {
                                return;
                            }

                            this._modules.removeAll();
                            for (const [id, label, on] of modules) {
                                const item = new PopupMenu.PopupSwitchMenuItem(label, on);
                                item.connect('toggled', (_item, state) =>
                                    callHub(SET_MODULE_ON, new GLib.Variant('(sb)', [id, state])));
                                this._modules.addMenuItem(item);
                            }

                            if (modules.length > 0)
                                this._modules.addMenuItem(new PopupMenu.PopupSeparatorMenuItem());
                        });
                }
            });

            function hides(icon) {
                const name = icon?.to_string?.() ?? '';
                return HIDDEN.some(prefix => name.startsWith(prefix));
            }

            export default class MosaicShellOsdGuard extends Extension {
                enable() {
                    this._indicator = null;
                    this._hubWatch = Gio.bus_watch_name(Gio.BusType.SESSION, HUB, Gio.BusNameWatcherFlags.NONE,
                        () => {
                            if (!this._indicator) {
                                this._indicator = new HubIndicator(this.dir);
                                Main.panel.addToStatusArea(this.uuid, this._indicator);
                            }
                        },
                        () => {
                            this._indicator?.destroy();
                            this._indicator = null;
                        });

                    this._guarded = false;
                    this._watch = Gio.bus_watch_name(Gio.BusType.SESSION, GUARD, Gio.BusNameWatcherFlags.NONE,
                        () => { this._guarded = true; },
                        () => { this._guarded = false; });
                    const manager = Main.osdWindowManager;
                    const original = manager._showOsdWindow;
                    this._original = original;
                    const guard = this;
                    manager._showOsdWindow = function (monitorIndex, icon, ...rest) {
                        if (guard._guarded && hides(icon))
                            return;
                        original.call(this, monitorIndex, icon, ...rest);
                    };
                }

                disable() {
                    if (this._hubWatch)
                        Gio.bus_unwatch_name(this._hubWatch);
                    this._hubWatch = 0;
                    this._indicator?.destroy();
                    this._indicator = null;

                    if (this._original)
                        Main.osdWindowManager._showOsdWindow = this._original;
                    if (this._watch)
                        Gio.bus_unwatch_name(this._watch);
                    this._original = null;
                    this._watch = 0;
                    this._guarded = false;
                }
            }

            """;

        /// <summary><c>$XDG_DATA_HOME/gnome-shell/extensions/&lt;uuid&gt;</c>, where Shell looks for a user's extensions.</summary>
        public static string InstallDirectory(string dataHome)
        {
            return dataHome.TrimEnd('/') + "/gnome-shell/extensions/" + Uuid;
        }

        /// <summary>Whether the extension skips the pop-up for a themed icon name.</summary>
        public static bool HidesIcon(string iconName)
        {
            return HiddenIconPrefixes.Any(prefix => iconName.StartsWith(prefix, StringComparison.Ordinal));
        }

        /// <summary>
        /// gsettings' <c>enabled-extensions</c> value with <see cref="Uuid"/> added, in the form gsettings prints
        /// (<c>@as []</c> or <c>['a@b', 'c@d']</c>); null when it is already there or the value cannot be read, so an
        /// unexpected list is never overwritten.
        /// </summary>
        public static string? EnabledListWithUuid(string? current)
        {
            if (current is null)
            {
                return null;
            }

            string trimmed = current.Trim();
            List<string> uuids;
            if (trimmed is "@as []" or "[]")
            {
                uuids = [];
            }
            else if (ListPattern().IsMatch(trimmed))
            {
                uuids = [.. ItemPattern().Matches(trimmed).Select(static m => m.Groups[1].Value)];
            }
            else
            {
                return null;
            }

            if (uuids.Contains(Uuid, StringComparer.Ordinal))
            {
                return null;
            }

            uuids.Add(Uuid);
            return "[" + string.Join(", ", uuids.Select(static u => "'" + u + "'")) + "]";
        }

        [GeneratedRegex(@"^\[\s*'[^']*'(\s*,\s*'[^']*')*\s*\]$")]
        private static partial Regex ListPattern();

        [GeneratedRegex(@"'([^']*)'")]
        private static partial Regex ItemPattern();
    }
